// Vendors the bundled Inter faces (SIL OFL 1.1) from the `@fontsource/inter` tarball into `fonts/`, checking the tarball's
// integrity and every file's sha256 against the pins below, and writes `src/presets/fontData.ts` (the same bytes as base64: the runtime
// reads that module, never a file path, because a bundled `import.meta.url` is not a file URL inside Next). Run it only to bump the faces.
//   node scripts/fetch-fonts.mjs
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const VERSION = '5.3.0'
const INTEGRITY = 'sha512-RofMylZmjlJEfELXeNHFWBRcSs75rGU/6bV2S2jfnvv/3rPXPGe0LgUJTklcHZ9lM4OZmAVFhcJPnACfb91A3g=='
const FILES = {
  'inter-latin-400-normal.woff': 'e20fa0b4fd2dd26e4d14b3ac3cc922509c3a63fa5e910e90c614544aa042dd45',
  'inter-latin-700-normal.woff': '7c5ed5655730de337704d3fc94628515cd7e3d8d32368871709bf56ac0397e7a',
  'inter-latin-ext-400-normal.woff': '22ae8360fbad24d2af7c6c9898a346c881774dc87f7cf94bd262c48ad58d7116',
  'inter-latin-ext-700-normal.woff': '1761edba32014180deab3dbbe3f7156c64ef6f34bc76313ba31ce227fc9ff391',
  'inter-cyrillic-400-normal.woff': '6e441a6c94788318fa02b6d0a633aa29eebe27b69c6567eb1e59b4edc68ed70e',
  'inter-cyrillic-700-normal.woff': '72b6daa49173e531027d8a260ef128e142a165811cab6a2875eefe0c3c58fa0e',
}
const sha256 = (file) => createHash('sha256').update(readFileSync(file)).digest('hex')

const work = mkdtempSync(join(tmpdir(), 'og-fonts-'))
const packed = JSON.parse(
  execFileSync('npm', ['pack', `@fontsource/inter@${VERSION}`, '--json', '--pack-destination', work], { encoding: 'utf8' }),
)[0]
if (packed.integrity !== INTEGRITY)
  throw new Error(`@fontsource/inter@${VERSION}: integrity ${packed.integrity} is not the pinned ${INTEGRITY}`)
execFileSync('tar', ['xzf', join(work, packed.filename), '-C', work])

const out = new URL('../fonts/', import.meta.url).pathname
mkdirSync(out, { recursive: true })
for (const [name, pin] of Object.entries(FILES)) {
  const from = join(work, 'package', 'files', name)
  if (sha256(from) !== pin) throw new Error(`${name}: sha256 ${sha256(from)} is not the pinned ${pin}`)
  copyFileSync(from, join(out, name))
}
copyFileSync(join(work, 'package', 'LICENSE'), join(out, 'OFL.txt'))
console.log(`vendored ${Object.keys(FILES).length} faces and OFL.txt from @fontsource/inter@${VERSION}`)

// The module the presets register the faces from: one constant per file, the bytes as base64.
const entries = Object.keys(FILES).map((name) => `  '${name}': '${readFileSync(join(out, name)).toString('base64')}',`)
writeFileSync(
  new URL('../src/presets/fontData.ts', import.meta.url).pathname,
  `// Generated by scripts/fetch-fonts.mjs from @fontsource/inter@${VERSION} (SIL OFL 1.1, see fonts/OFL.txt). Do not edit.\n` +
    `export const INTER_VERSION = '${VERSION}'\n` +
    `/** The faces of \`fonts/\`, base64 by file name. */\n` +
    `export const FONT_DATA: Record<string, string> = {\n${entries.join('\n')}\n}\n`,
)
console.log('wrote src/presets/fontData.ts')
